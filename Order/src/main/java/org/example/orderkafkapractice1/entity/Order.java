package org.example.orderkafkapractice1.entity;

import java.math.BigDecimal;

public class Order {

    private Long id;

    private String name;

    private BigDecimal price;

    private Long amount;

    public Order() {
    }

    public Order(Long id, String name, BigDecimal price, Long amount) {
        this.id = id;
        this.name = name;
        this.price = price;
        this.amount = amount;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public Long getAmount() {
        return amount;
    }

    public void setAmount(Long amount) {
        this.amount = amount;
    }
}
